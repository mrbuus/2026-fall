/* Лаборатори №8 (8-1 даалгавар)
   A[8] нэг хэмжээст массивын элементүүдээс өгөгдсөн тоо X-ээс бага утгыг
   тоолж, ямар дугаартай, ямар утгатай элементүүд энэ нөхцлийг хангаж
   байгааг хэвлэх. */
#include <stdio.h>

int main()
{
    int A[8];
    int i, X, c;

    for (i = 0; i < 8; i++)
    {
        printf("A[%d] = ", i);
        scanf("%d", &A[i]);
    }

    printf("X = ");
    scanf("%d", &X);

    c = 0;
    for (i = 0; i < 8; i++)
    {
        if (A[i] < X)
        {
            printf("A[%d] = %d\n", i, A[i]);
            c++;
        }
    }

    printf("X-ээс бага элементийн тоо = %d\n", c);

    return 0;
}
