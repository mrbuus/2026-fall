/* Лаборатори №8 (8-3 даалгавар)
   a1, ..., a20 бодит тоонууд өгөгдөв. Дараах дарааллыг гарган ав:
   a20, a10, a19, a9, ..., a11, a1
   (сүүлийн хагасаас нэг, эхний хагасаас нэгийг ээлжлэн, ардаас нь авна) */
#include <stdio.h>

#define N 20

int main()
{
    double a[N];
    int i;

    for (i = 0; i < N; i++)
    {
        printf("a%d = ", i + 1);
        scanf("%lf", &a[i]);
    }

    /* a[19] = a20, a[9] = a10 гэх мэт */
    for (i = N - 1; i >= N / 2; i--)
    {
        printf("%.2f %.2f ", a[i], a[i - N / 2]);
    }
    printf("\n");

    return 0;
}
