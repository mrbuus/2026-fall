/* Лаборатори №2, Даалгавар 1a
   Гурвалжны 3 тал өгөгдсөн үед талбайг Героны томьёогоор олох.
   S = sqrt(p*(p-a)*(p-b)*(p-c)),  p = (a+b+c)/2                       */
#include <stdio.h>
#include <math.h>

int main(void)
{
    double a, b, c, p, S;

    printf("Гурвалжны 3 талыг оруулна уу (a b c): ");
    if (scanf("%lf %lf %lf", &a, &b, &c) != 3) {
        printf("Буруу өгөгдөл.\n");
        return 1;
    }

    /* Гурвалжин орших нөхцөл: тал бүр эерэг ба хоёр талын нийлбэр
       гуравдахиасаа их байх ёстой. */
    if (a <= 0 || b <= 0 || c <= 0) {
        printf("Талын урт эерэг тоо байх ёстой.\n");
        return 1;
    }
    if (a + b <= c || a + c <= b || b + c <= a) {
        printf("Ийм талуудтай гурвалжин орших боломжгүй.\n");
        return 1;
    }

    p = (a + b + c) / 2.0;              /* хагас периметр */
    S = sqrt(p * (p - a) * (p - b) * (p - c));

    printf("Периметрийн хагас p = %.4f\n", p);
    printf("Талбай          S = %.4f\n", S);
    return 0;
}
