/* Лаборатори №2, Нэмэлт даалгавар 4
   Ялгавар нь 2 байх 15 хосыг хэвлэ. Жишээ: (3, 5) (11, 13) ...
   Жишээнд өгсөн хосууд нь хоёулаа анхны тоо тул ялгавар нь 2 байх анхны
   тоонуудын (ихэр анхны тоонуудын) эхний 15 хосыг хэвлэнэ. */
#include <stdio.h>

int main()
{
    int n, d, too, anhnii_n, anhnii_n2;

    too = 0;
    n = 3;
    while (too < 15)
    {
        /* n анхны тоо мөн эсэх */
        anhnii_n = 1;
        d = 2;
        while (d * d <= n)
        {
            if (n % d == 0)
                anhnii_n = 0;
            d++;
        }

        /* n + 2 анхны тоо мөн эсэх */
        anhnii_n2 = 1;
        d = 2;
        while (d * d <= n + 2)
        {
            if ((n + 2) % d == 0)
                anhnii_n2 = 0;
            d++;
        }

        if (anhnii_n == 1 && anhnii_n2 == 1)
        {
            too++;
            printf("%2d) (%d, %d)\n", too, n, n + 2);
        }

        n = n + 2;
    }

    return 0;
}
