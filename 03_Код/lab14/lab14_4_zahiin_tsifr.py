# 4 оронтой тооны хамгийн зүүн ба баруун талын цифрийг хэвлэх.

n = int(input("4 оронтой тоо оруул: "))

if 1000 <= n <= 9999:
    zuun = n // 1000
    baruun = n % 10
    print("Зүүн талын цифр:", zuun)
    print("Баруун талын цифр:", baruun)
else:
    print("4 оронтой тоо биш байна!")
