/* Лаборатори №9 (9-2 даалгавар)
   Инженерийн ангид 20 оюутан 6 улирал суралцсан.
   - Хамгийн өндөр ҮГД авсан оюутан хэддүгээр улиралд хэддэх оюутан болохыг ол.
   - Ангийн дундажаас дээш ҮГД-тэй хэдэн тохиолдол байгааг ол.
   S[i][j] нь i-р улиралд j-р оюутны авсан ҮГД. */
#include <stdio.h>

int main()
{
    int a, b, i, j, k, m, c, deesh;
    float max, sum, avg, S[6][20];

    printf("Хэдэн улирлын ҮГД оруулах вэ? (<=6): ");
    scanf("%d", &a);
    printf("Хэдэн оюутны ҮГД оруулах вэ? (<=20): ");
    scanf("%d", &b);

    for (i = 0; i < a; i++)
    {
        for (j = 0; j < b; j++)
        {
            printf("%d-р улирал, %d-р оюутан: ", i + 1, j + 1);
            scanf("%f", &S[i][j]);
        }
    }

    sum = 0;
    c = 0;
    max = S[0][0];
    k = 0;
    m = 0;
    for (i = 0; i < a; i++)
    {
        for (j = 0; j < b; j++)
        {
            sum = sum + S[i][j];
            c++;
            if (max < S[i][j])
            {
                max = S[i][j];
                k = i;
                m = j;
            }
        }
    }

    avg = sum / c;

    printf("\nХамгийн өндөр ҮГД = %.2f\n", max);
    printf("%d-р улиралд %d-р оюутан авсан\n", k + 1, m + 1);
    printf("Ангийн дундаж ҮГД = %.4f\n", avg);

    deesh = 0;
    for (i = 0; i < a; i++)
    {
        for (j = 0; j < b; j++)
        {
            if (S[i][j] > avg)
                deesh++;
        }
    }

    printf("Дундажаас дээш ҮГД-тэй тохиолдлын тоо = %d\n", deesh);

    return 0;
}
