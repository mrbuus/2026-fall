/* Лаборатори №7 (массивын бодлого 1)
   10 бүхэл тоон элементтэй A массивын элементийн утгыг индексийг 3 дахин
   ихэсгээд 1-ээр нэмэгдүүлж олох (A[i] = 3*i + 1) ба элементүүдийн
   үржвэрийг олох. */
#include <stdio.h>

int main()
{
    int A[10];
    int i;
    long long p = 1;

    printf("%s%10s\n", "Индекс", "Утга");

    for (i = 0; i < 10; i++)
    {
        A[i] = 3 * i + 1;
        printf("%6d %10d\n", i, A[i]);
        p = p * A[i];
    }

    printf("\nЭлементүүдийн үржвэр = %lld\n", p);

    return 0;
}
