/* Лаборатори №7 (массивын бодлого 2)
   Таван бодит тоон утгатай массивын элементүүдэд 1 гэсэн утга олгож хэвлэх. */
#include <stdio.h>

int main()
{
    float B[5];
    int i;

    for (i = 0; i < 5; i++)
    {
        B[i] = 1;
    }

    for (i = 0; i < 5; i++)
    {
        printf("B[%d] = %.1f\n", i, B[i]);
    }

    return 0;
}
