/* Бодлого 53
   a, b, c, d, e, f, g, h бодит тоонууд өгөгдөв. (e, f) ба (g, h) нь
   ялгаатай цэгүүд. (a, b) ба (c, d) цэгүүд (e, f), (g, h) цэгүүдийг дайрах
   l шулуун дээр оршихгүй. l шулуун хавтгайг хоёр хагас хавтгайд хуваана.
   (a, b) ба (c, d) цэгүүд нэг ижил хагас хавтгайд орших эсэхийг тодорхойл.

   l шулууны тэгшитгэл: (x-e)(h-f) - (y-f)(g-e) = 0.
   Хоёр цэгийг орлуулахад гарах утгууд ижил тэмдэгтэй бол нэг хагас
   хавтгайд оршино. */
#include <stdio.h>

int main()
{
    double a, b, c, d, e, f, g, h;
    double F1, F2;

    printf("(a, b) цэг: ");
    scanf("%lf %lf", &a, &b);
    printf("(c, d) цэг: ");
    scanf("%lf %lf", &c, &d);
    printf("(e, f) цэг: ");
    scanf("%lf %lf", &e, &f);
    printf("(g, h) цэг: ");
    scanf("%lf %lf", &g, &h);

    if (e == g && f == h)
    {
        printf("(e, f) ба (g, h) цэгүүд ялгаатай байх ёстой!\n");
        return 0;
    }

    F1 = (a - e) * (h - f) - (b - f) * (g - e);
    F2 = (c - e) * (h - f) - (d - f) * (g - e);

    if (F1 == 0 || F2 == 0)
        printf("Цэг l шулуун дээр оршиж байна!\n");
    else if (F1 * F2 > 0)
        printf("(a, b) ба (c, d) цэгүүд нэг хагас хавтгайд оршино\n");
    else
        printf("(a, b) ба (c, d) цэгүүд өөр өөр хагас хавтгайд оршино\n");

    return 0;
}
